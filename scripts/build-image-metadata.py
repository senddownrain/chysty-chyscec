"""Build runtime metadata and the public per-image credits from the reviewed registry."""
import html,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
registry=json.loads((ROOT/'docs/image-rights.json').read_text())
runtime={}
e=html.escape
sections=[]
for row in registry['images']:
    approved=row['status']=='verified' and row['decision']=='accepted'
    if approved:
        w=row['web'];a=row['attribution']
        assert w and a and row['evidence'] and a['sourcePage'] and a['licenseURL']
        runtime[row['id']]={k:w[k] for k in ['width','height','src','srcset','sizes','print']}
        runtime[row['id']].update(credit=a['credit'],source=a['sourcePage'],license=a['license'],licenseURL=a['licenseURL'])
        content=f'<p>{e(a["author"])} — {e(a["title"])}. {e(a["institution"])}.</p><p><a href="{e(a["sourcePage"])}">Старонка твора</a> · <a href="{e(a["originalFile"])}">Арыгінальны файл</a> · <a href="{e(a["licenseURL"])}">{e(a["license"])}</a> · <a href="{e(a["legalCode"])}">Прававы тэкст</a>.</p><p>Змены: прапарцыянальнае памяншэнне і сцісканне WebP. Без абрэзкі і павелічэння; палі задаюцца CSS. Арыгінал і вытворныя: CC0 1.0. Аўтар і крыніца захаваныя добраахвотна.</p>'
    else:
        assert row['web'] is None, row['id']
        runtime[row['id']]=None
        content='<p>Выява не выкарыстоўваецца: правы або адпаведнасць асобы яшчэ патрабуюць праверкі. Картка і друк даступныя без выявы.</p>'
    sections.append(f'<section id="{e(row["id"])}"><h3>{e(row["id"])} · {e(row["name"])}</h3>{content}</section>')
(ROOT/'image-sizes.mjs').write_text('// Generated by scripts/build-image-metadata.py; only accepted, verified images.\nexport const imageSizes='+json.dumps(runtime,ensure_ascii=False,indent=2)+';\n')
path=ROOT/'sources.html';s=path.read_text()
start='<!-- BEGIN SAINT IMAGE RIGHTS -->';end='<!-- END SAINT IMAGE RIGHTS -->'
replacement=start+'\n<h2>Крыніцы і правы на выявы святых</h2>\n'+'\n'.join(sections)+'\n'+end
assert start in s and end in s
s=s[:s.index(start)]+replacement+s[s.index(end)+len(end):]
path.write_text(s)
